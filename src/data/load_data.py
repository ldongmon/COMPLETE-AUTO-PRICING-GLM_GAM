"""
load_data.py
============
Fetch-and-cache logic for the freMTPL2freq / freMTPL2sev dataset.

WHY THIS LIVES IN src/, NOT IN A NOTEBOOK
------------------------------------------
Every notebook and the Streamlit app all need the *exact same* raw data,
loaded the *exact same* way. If the download/cast logic were copy-pasted into
each notebook, a fix made in notebook 03 would silently not apply to
notebook 01's re-run, and two "identical" analyses could quietly disagree.
Putting it here, once, and importing it everywhere keeps every analysis on
the same data.

WHAT THIS MODULE DOES
----------------------
1. Downloads freMTPL2freq (OpenML data id 41214) and freMTPL2sev (data id
   41215) via scikit-learn's `fetch_openml`, which handles the OpenML API
   call and ARFF parsing for us.
2. Caches each table as a local Parquet file under data/raw/, so every
   subsequent call is instant and offline: we hit the network at most once.
3. Normalizes dtypes. OpenML's ARFF loader tends to return integer-valued
   columns as float64 (ARFF has no native "int" type distinct from
   "numeric"), and categorical columns sometimes carry a leading/trailing
   quote character. We fix both here so downstream code never has to guess.

Usage
-----
    from src.data.load_data import load_freq_raw, load_sev_raw

    df_freq = load_freq_raw()
    df_sev  = load_sev_raw()

Or from the command line, to (re)populate the cache and print a quick summary:

    python -m src.data.load_data
"""

from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd
from sklearn.datasets import fetch_openml

logger = logging.getLogger(__name__)

# --------------------------------------------------------------------------- #
# Constants
# --------------------------------------------------------------------------- #

# OpenML dataset ids: stable, permanent identifiers (unlike dataset *names*,
# which can be reused by different uploaders). Pinning by id is the
# reproducible choice.
OPENML_ID_FREQ = 41214  # freMTPL2freq: one row per policy
OPENML_ID_SEV = 41215  # freMTPL2sev: one row per claim payment

# Where the cached, cleaned-dtype raw tables live. Kept out of git
# (see .gitignore): data is regenerated by this module, never committed.
_PROJECT_ROOT = Path(__file__).resolve().parents[2]
RAW_DATA_DIR = _PROJECT_ROOT / "data" / "raw"

FREQ_CACHE_PATH = RAW_DATA_DIR / "freMTPL2freq.parquet"
SEV_CACHE_PATH = RAW_DATA_DIR / "freMTPL2sev.parquet"

# Columns we expect on freMTPL2freq, and the dtype we want each one to end up
# as *after* cleaning. Declaring this explicitly (rather than trusting
# whatever OpenML hands back) is what makes the loader fail loudly if the
# upstream schema ever changes, instead of silently passing bad dtypes
# downstream into a GLM.
FREQ_DTYPES = {
    "IDpol": "int64",
    "ClaimNb": "int64",
    "Exposure": "float64",
    "Area": "category",
    "VehPower": "int64",
    "VehAge": "int64",
    "DrivAge": "int64",
    "BonusMalus": "int64",
    "VehBrand": "category",
    "VehGas": "category",
    "Density": "float64",
    "Region": "category",
}

SEV_DTYPES = {
    "IDpol": "int64",
    "ClaimAmount": "float64",
}


# --------------------------------------------------------------------------- #
# Internal helpers
# --------------------------------------------------------------------------- #


def _strip_quotes(series: pd.Series) -> pd.Series:
    """
    ARFF categorical values are sometimes wrapped in single quotes by the
    OpenML/liac-arff parser (e.g. "'B12'" instead of "B12"). Strip them so
    category labels are clean and match what a human reading a plot expects.
    """
    if series.dtype == object or str(series.dtype) == "category":
        return series.astype(str).str.strip("'").astype("category")
    return series


def _download_freq() -> pd.DataFrame:
    """Pull freMTPL2freq from OpenML and coerce it to FREQ_DTYPES."""
    logger.info("Downloading freMTPL2freq (OpenML id=%s): this hits the network once.", OPENML_ID_FREQ)
    bunch = fetch_openml(data_id=OPENML_ID_FREQ, as_frame=True, parser="liac-arff")
    df = bunch.frame.copy()

    # Defensive: fail loudly (not with a confusing downstream KeyError) if the
    # upstream schema no longer matches what this project was built against.
    missing = set(FREQ_DTYPES) - set(df.columns)
    if missing:
        raise ValueError(f"freMTPL2freq is missing expected columns: {missing}")

    df = df[list(FREQ_DTYPES.keys())]
    # Explicit dtype-name check rather than select_dtypes(include=["object", "category"]):
    # pandas 3's new string dtype makes select_dtypes(include="object") ambiguous/deprecated
    # for columns holding text, so we check dtype names directly instead.
    categorical_cols = [c for c in df.columns if str(df[c].dtype) in ("object", "category", "str")]
    for col in categorical_cols:
        df[col] = _strip_quotes(df[col])

    df = df.astype(FREQ_DTYPES)
    return df


def _download_sev() -> pd.DataFrame:
    """Pull freMTPL2sev from OpenML and coerce it to SEV_DTYPES."""
    logger.info("Downloading freMTPL2sev (OpenML id=%s): this hits the network once.", OPENML_ID_SEV)
    bunch = fetch_openml(data_id=OPENML_ID_SEV, as_frame=True, parser="liac-arff")
    df = bunch.frame.copy()

    missing = set(SEV_DTYPES) - set(df.columns)
    if missing:
        raise ValueError(f"freMTPL2sev is missing expected columns: {missing}")

    df = df[list(SEV_DTYPES.keys())].astype(SEV_DTYPES)
    return df


# --------------------------------------------------------------------------- #
# Public API
# --------------------------------------------------------------------------- #


def load_freq_raw(force_download: bool = False) -> pd.DataFrame:
    """
    Load the raw (uncleaned-of-quirks, but dtype-normalized) policy-level
    frequency table, one row per policy as it appears in the source file
    (no row is dropped here: every cleaning step, such as the claims-only
    block exclusion, is a documented decision made in Phase 1).

    Parameters
    ----------
    force_download : bool
        If True, ignore any local Parquet cache and re-download from OpenML.

    Returns
    -------
    pd.DataFrame with columns per FREQ_DTYPES.
    """
    RAW_DATA_DIR.mkdir(parents=True, exist_ok=True)

    if FREQ_CACHE_PATH.exists() and not force_download:
        logger.info("Loading freMTPL2freq from cache: %s", FREQ_CACHE_PATH)
        return pd.read_parquet(FREQ_CACHE_PATH)

    df = _download_freq()
    df.to_parquet(FREQ_CACHE_PATH, index=False)
    logger.info("Cached freMTPL2freq to %s (%d rows).", FREQ_CACHE_PATH, len(df))
    return df


def load_sev_raw(force_download: bool = False) -> pd.DataFrame:
    """
    Load the raw claim-level severity table, one row per claim payment.

    Parameters
    ----------
    force_download : bool
        If True, ignore any local Parquet cache and re-download from OpenML.

    Returns
    -------
    pd.DataFrame with columns per SEV_DTYPES.
    """
    RAW_DATA_DIR.mkdir(parents=True, exist_ok=True)

    if SEV_CACHE_PATH.exists() and not force_download:
        logger.info("Loading freMTPL2sev from cache: %s", SEV_CACHE_PATH)
        return pd.read_parquet(SEV_CACHE_PATH)

    df = _download_sev()
    df.to_parquet(SEV_CACHE_PATH, index=False)
    logger.info("Cached freMTPL2sev to %s (%d rows).", SEV_CACHE_PATH, len(df))
    return df


def find_claims_only_block_end(freq: pd.DataFrame) -> int:
    """
    Return the last IDpol of the leading claims-only block of freMTPL2freq.

    The first IDpol values of freMTPL2freq do not come from the same extract
    as the rest of the portfolio: every policy up to IDpol 24,951 carries at
    least one reported claim (no claim-free policy at all), the implied claim
    frequency is above 100%, and only about 3% of those claims have a payment
    in freMTPL2sev. Above that IDpol, 99.9% of reported claims have a payment.
    The block is therefore a claims file appended to the portfolio, not a
    sample of it, and it is excluded from modeling (Phase 1).

    The boundary is found from the data, not hard-coded: it is the IDpol just
    before the first policy with ClaimNb == 0.
    """
    ordered = freq.sort_values("IDpol")
    first_claim_free = ordered.loc[ordered["ClaimNb"] == 0, "IDpol"].min()
    below = ordered.loc[ordered["IDpol"] < first_claim_free, "IDpol"]
    return int(below.max()) if len(below) else 0


def drop_claims_only_block(df: pd.DataFrame, block_end: int) -> pd.DataFrame:
    """Drop every policy with IDpol <= `block_end` (see `find_claims_only_block_end`)."""
    return df.loc[df["IDpol"] > block_end].reset_index(drop=True)


# --------------------------------------------------------------------------- #
# CLI entry point: `python -m src.data.load_data`
# --------------------------------------------------------------------------- #

if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

    freq = load_freq_raw()
    sev = load_sev_raw()

    print("\n=== freMTPL2freq ===")
    print(f"Rows: {len(freq):,} | Unique IDpol: {freq['IDpol'].nunique():,}")
    print(freq.dtypes)

    print("\n=== freMTPL2sev ===")
    print(f"Rows: {len(sev):,} | Unique IDpol (policies with >=1 claim payment): {sev['IDpol'].nunique():,}")
    print(sev.dtypes)
